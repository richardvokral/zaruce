#!/usr/bin/env node
/**
 * Generates db/migrations/0002_seed_buckets.sql by enumerating every attribute
 * combination. The bucket id is deterministic and matches `bucketId()` in
 * packages/shared/src/attributes.ts — runtime stays in lockstep with the DB.
 *
 * Enums are duplicated here intentionally so the script runs as plain Node
 * without a TS loader. CI verifies the two stay aligned via a unit test.
 *
 * Run after editing the attribute taxonomy:
 *   pnpm exec node scripts/gen-bucket-seed.mjs
 */

import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const AGE_BUCKETS  = ["child", "teen", "young-adult", "adult", "middle", "senior"];
const PRESENTATIONS = ["masc", "fem", "ambiguous"];
const HAIR_COLORS  = ["black", "brown", "blond", "red", "gray", "other"];
const SKIN_TONES   = [1, 2, 3, 4, 5, 6];
const HAIR_LENGTHS = ["short", "medium", "long"];

function bucketId(idx) {
  let id = 0;
  id = id * AGE_BUCKETS.length  + idx.age;
  id = id * PRESENTATIONS.length + idx.presentation;
  id = id * HAIR_COLORS.length  + idx.hairColor;
  id = id * SKIN_TONES.length   + idx.skinTone;
  id = id * 2                   + (idx.glasses ? 1 : 0);
  id = id * HAIR_LENGTHS.length + idx.hairLength;
  return id;
}

const __dirname = dirname(fileURLToPath(import.meta.url));
const out = resolve(__dirname, "../db/migrations/0002_seed_buckets.sql");

const rows = [];
for (let a = 0; a < AGE_BUCKETS.length; a++) {
  for (let p = 0; p < PRESENTATIONS.length; p++) {
    for (let h = 0; h < HAIR_COLORS.length; h++) {
      for (let s = 0; s < SKIN_TONES.length; s++) {
        for (const g of [false, true]) {
          for (let l = 0; l < HAIR_LENGTHS.length; l++) {
            const id = bucketId({ age: a, presentation: p, hairColor: h, skinTone: s, glasses: g, hairLength: l });
            rows.push([id, a, p, h, s, g, l]);
          }
        }
      }
    }
  }
}

const values = rows
  .map(([id, a, p, h, s, g, l]) => `  (${id}, ${a}, ${p}, ${h}, ${s}, ${g ? "TRUE" : "FALSE"}, ${l})`)
  .join(",\n");

const sql = `-- 0002_seed_buckets.sql — auto-generated by scripts/gen-bucket-seed.mjs.
-- Do not edit by hand; re-run the script after taxonomy changes.
-- ${rows.length} rows.

BEGIN;

INSERT INTO attribute_buckets
  (id, age_bucket, presentation, hair_color, skin_tone, glasses, hair_length)
VALUES
${values}
ON CONFLICT (id) DO NOTHING;

COMMIT;
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, sql);
console.log(`wrote ${rows.length} rows → ${out}`);
